    id VARCHAR(64) PRIMARY KEY,
    snapshot_id VARCHAR(64) NOT NULL REFERENCES sql_analyzer.profile_snapshot(id) ON DELETE CASCADE,
    schema_name VARCHAR(200),
    table_name VARCHAR(300) NOT NULL,
    column_name VARCHAR(300) NOT NULL,
    null_ratio DOUBLE PRECISION,
    approx_distinct BIGINT,
    min_value TEXT,
    max_value TEXT,
    top_k_json TEXT NOT NULL DEFAULT '[]',
    buckets_json TEXT NOT NULL DEFAULT '[]',
    quantiles_json TEXT NOT NULL DEFAULT '[]',
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_profile_column_stat_snapshot ON sql_analyzer.profile_column_stat(snapshot_id);

-- ---------- AgentScope state (H2) ----------
-- The official PostgresDistributedStore self-creates its own tables on PostgreSQL; on H2 the
-- product-provided persistent AgentStateStore + BaseStore (docs/cloud-code-next-goal.md §3.6)
-- use these Flyway-managed tables. Keyed by (user_id = authenticated clientId, session_id).

CREATE SCHEMA IF NOT EXISTS agentscope;

CREATE TABLE agentscope.agent_state (
    user_id VARCHAR(255) NOT NULL,
    session_id VARCHAR(255) NOT NULL,
    state_key VARCHAR(255) NOT NULL,
    item_index INTEGER NOT NULL DEFAULT 0,
    state_data TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, session_id, state_key, item_index)
);

-- NOTE: agentscope.kv_store is created by the portable common migration (version 10) on both
-- databases; the H2 AgentState table above has no PostgreSQL equivalent because the official
-- PostgresAgentStateStore self-creates its own table there.
